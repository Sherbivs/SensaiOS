#!/usr/bin/env node
/**
 * Setup Git Hooks for Metric Accuracy Verification
 * 
 * Installs pre-commit hook that prevents committing code with hardcoded estimates.
 * 
 * Usage:
 *   node scripts/setup-git-hooks.mjs
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const HOOKS_DIR = path.join(__dirname, '..', '.git', 'hooks');
const PRE_COMMIT_HOOK = path.join(HOOKS_DIR, 'pre-commit');
const SOURCE_HOOK = path.join(__dirname, 'pre-commit-metrics.mjs');

function main() {
  console.log('🔧 Setting up Git hooks for metric accuracy verification...\n');

  // Check if .git directory exists
  if (!fs.existsSync(HOOKS_DIR)) {
    console.error('❌ Error: .git/hooks directory not found.');
    console.error('   Make sure you are in a git repository.\n');
    process.exit(1);
  }

  // Check if pre-commit hook already exists
  if (fs.existsSync(PRE_COMMIT_HOOK)) {
    console.log('⚠️  Pre-commit hook already exists.');
    console.log('   Backing up to pre-commit.backup...\n');
    fs.copyFileSync(PRE_COMMIT_HOOK, `${PRE_COMMIT_HOOK}.backup`);
  }

  // Create the pre-commit hook
  const hookContent = `#!/bin/sh
# Metric Accuracy Verification Pre-commit Hook
# Generated by scripts/setup-git-hooks.mjs

node scripts/pre-commit-metrics.mjs
`;

  fs.writeFileSync(PRE_COMMIT_HOOK, hookContent, { mode: 0o755 });

  console.log('✅ Pre-commit hook installed successfully!\n');
  console.log('The hook will now run on every commit to check for:');
  console.log('  - Magic numbers (50, 100, 500, etc.) in metric code');
  console.log('  - Estimate keywords (about, roughly, approximately, etc.)');
  console.log('  - Estimate patterns (~50, ≈100, etc.)\n');
  console.log('To skip the hook (NOT RECOMMENDED), use:');
  console.log('  SKIP_METRICS_HOOK=1 git commit ...\n');
  console.log('To test the hook manually:');
  console.log('  node scripts/verify-metrics-accuracy.mjs --staged\n');
}

try {
  main();
} catch (error) {
  console.error('❌ Error setting up hooks:', error.message);
  process.exit(1);
}
