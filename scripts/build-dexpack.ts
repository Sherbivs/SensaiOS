function hashString(value: string): number {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

function nextPowerOfTwo(value: number): number {
  let size = 1;
  while (size < value) {
    size <<= 1;
  }
  return size;
}

export type HashTablePayload = {
  size: number;
  ids: number[];
  keys: string[];
};

function buildHashTable(entries: Array<[string, number]>): HashTablePayload {
  if (entries.length === 0) {
    return { size: 0, ids: [], keys: [] };
  }

  const size = nextPowerOfTwo(entries.length * 2);
  const mask = size - 1;
  const ids = new Array<number>(size).fill(-1);
  const keys = new Array<string>(size).fill("");

  for (const [key, value] of entries) {
    const hash = hashString(key);
    let index = hash & mask;
    let step = (hash >>> 16) & mask;
    if (step === 0) {
      step = 1;
    }

    for (let attempt = 0; attempt < size; attempt += 1) {
      if (ids[index] === -1) {
        ids[index] = value;
        keys[index] = key;
        break;
      }
      index = (index + step) & mask;
    }
  }

  return {
    size,
    ids,
    keys,
  };
}

function normalizeKey(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeLookup(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

