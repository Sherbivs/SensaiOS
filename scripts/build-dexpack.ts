export async function buildDexpackContext(): Promise<DexpackBuildContext> {
  const [dexEntries, moveEntries, versionMeta, triggerMeta] = await Promise.all([
    loadJson<DexEntry[]>("data/bootstrap/dex.min.json"),
    loadJson<Record<string, MoveEntry>>("data/bootstrap/moves.min.json"),
    loadJson<VersionMeta>("data/bootstrap/version.json"),
    fs
      .readFile(path.join(CACHE_DIR, "dex-sync-trigger.json"), "utf8")
      .then((contents) => JSON.parse(contents) as TriggerMeta)
      .catch(() => ({}) as TriggerMeta),
  ]);

  if (!Array.isArray(dexEntries) || dexEntries.length === 0) {
    throw new Error("dex.min.json did not contain any species records");
  }

  const movesUnsorted: Record<string, MoveDoc> = {};
  for (const [slugRaw, move] of Object.entries(moveEntries)) {
    const slug = normalizeKey(slugRaw);
    if (!slug || typeof move?.id !== "number") continue;
    const category = move.class?.toLowerCase() ?? null;
    movesUnsorted[slug] = {
      id: move.id,
      name: move.name ?? slugRaw,
      slug,
      type: move.type ? normalizeKey(move.type) : null,
      category,
      power: typeof move.power === "number" ? move.power : null,
      accuracy: typeof move.accuracy === "number" ? move.accuracy : null,
      pp: typeof move.pp === "number" ? move.pp : null,
      priority: typeof move.priority === "number" ? move.priority : 0,
      target: move.target ?? null,
      effect: move.effect ?? null,
      meta: move.meta ?? null,
    } satisfies MoveDoc;
  }

  const speciesDocs = dexEntries
    .map((entry) => buildSpeciesDoc(entry))
    .sort((a, b) => a.id - b.id);

  const byId: Record<string, SpeciesDoc> = {};
  const byName: Record<string, number> = {};
  const byAlias: Record<string, number> = {};

  for (const doc of speciesDocs) {
    byId[String(doc.id)] = doc;
    const canonicalKeys = dedupe([normalizeLookup(doc.name), normalizeLookup(doc.slug)]);
    for (const key of canonicalKeys) {
      if (key) {
        byName[key] = doc.id;
      }
    }
    for (const alias of doc.aliases) {
      const key = normalizeLookup(alias);
      if (key && !(key in byAlias)) {
        byAlias[key] = doc.id;
      }
    }
  }

  for (const [aliasRaw, target] of Object.entries(ALIASES)) {
    const key = normalizeLookup(aliasRaw);
    const normalizedTarget = normalizeLookup(target);
    const id = byName[normalizedTarget];
    if (key && id) {
      byAlias[key] = id;
    }
  }

  const sortedById = sortRecord(byId, true);
  const sortedByName = sortRecord(byName);
  const sortedByAlias = sortRecord(byAlias);
  const sortedMoves = sortRecord(movesUnsorted);

  const pack: DexPack = {
    meta: {
      schema: "dexpack.v1",
      generatedAt:
        (typeof triggerMeta.updatedAt === "string" && triggerMeta.updatedAt.length > 0
          ? triggerMeta.updatedAt
          : null) ??
        (typeof versionMeta.built_at === "string" && versionMeta.built_at.length > 0
          ? versionMeta.built_at
          : null) ??
        "1970-01-01T00:00:00.000Z",
      source: {
        versionGroup: versionMeta.version_group ?? null,
        versionGroupId: typeof versionMeta.version_group_id === "number" ? versionMeta.version_group_id : null,
        builtAt: versionMeta.built_at ?? null,
        cacheChecksum: typeof triggerMeta.checksum === "string" ? triggerMeta.checksum : null,
        cacheCount: typeof triggerMeta.count === "number" ? triggerMeta.count : null,
        cacheUpdatedAt: triggerMeta.updatedAt ?? null,
      },
      counts: {
        species: speciesDocs.length,
        moves: Object.keys(sortedMoves).length,
      },
    },
    byId: sortedById,
    byName: sortedByName,
    byAlias: sortedByAlias,
    moves: sortedMoves,
    types: {
      order: [...TYPE_ORDER],
      chart: (() => {
        const chart = buildTypeChart();
        const sorted: Record<string, Record<string, number>> = {};
        for (const atk of TYPE_ORDER) {
          const row = chart[atk];
          const sortedRow: Record<string, number> = {};
          for (const def of TYPE_ORDER) {
            sortedRow[def] = row[def];
          }
          sorted[atk] = sortedRow;
        }
        return sorted;
      })(),
    },
  } satisfies DexPack;

  const vectors = buildSpeciesVectors(speciesDocs);
  const nameHash = buildHashTable(Object.entries(sortedByName));
  const aliasHash = buildHashTable(Object.entries(sortedByAlias));

  return {
    pack,
    speciesDocs,
    moves: sortedMoves,
    nameHash,
    aliasHash,
    vectors,
    versionMeta,
    triggerMeta,
  } satisfies DexpackBuildContext;
}

type ExpectedOutput = { filePath: string; buffer: Buffer };

async function verifyOutputs(outputs: ExpectedOutput[]): Promise<void> {
  const mismatches: string[] = [];

  for (const { filePath, buffer } of outputs) {
    const current = await readFileIfExists(filePath);
    if (!current) {
      mismatches.push(`${path.relative(ROOT, filePath)} is missing`);
      continue;
    }
    if (!buffersEqual(current, buffer)) {
      mismatches.push(`${path.relative(ROOT, filePath)} differs from generated output`);
    }
  }

  if (mismatches.length > 0) {
    const message = [`Dexpack artifacts are stale:`]
      .concat(mismatches.map((entry) => `- ${entry}`))
      .concat(['Run "npm run data:dexpack" to regenerate and commit the updated assets.'])
      .join("\n");
    throw new Error(message);
  }
}

type PendingOutput = { filePath: string; contents: string | Buffer };

async function writeOutputs(outputs: PendingOutput[]): Promise<boolean> {
  let updated = false;
  for (const { filePath, contents } of outputs) {
    const wrote = await writeFileIfChanged(filePath, contents);
    updated = updated || wrote;
  }
  return updated;
}

type CliOptions = {
  check?: boolean;
  quiet?: boolean;
};

function parseCliArgs(): CliOptions {
  const args = process.argv.slice(2);
  const options: CliOptions = { check: false, quiet: false };
  for (const arg of args) {
    if (arg === "--check") {
      options.check = true;
    } else if (arg === "--quiet") {
      options.quiet = true;
    } else if (arg === "--help" || arg === "-h") {
      console.log(
        formatList([
          "Usage: tsx scripts/build_dexpack.ts [--check] [--quiet]",
          "--check   Verify committed artifacts match regenerated output (no writes)",
          "--quiet   Suppress success logging",
        ])
      );
      process.exit(0);
    } else {
      console.log(formatStatus(`Unknown flag: ${arg}`, "warning"));
    }
  }
  return options;
}

async function main(options: CliOptions = {}): Promise<void> {
  const checkOnly = Boolean(options.check);
  const quiet = Boolean(options.quiet);
  log.info("dexpack", "Dexpack build started", { checkOnly, quiet });
  const { pack, nameHash, aliasHash, vectors } = await buildDexpackContext();

  await ensureOutputDir();
  const json = JSON.stringify(pack);
  const jsonWithNewline = `${json}\n`;
  const gzBuffer = gzipSync(Buffer.from(json));
  const statIndexLiteral = vectors.statIndex.join(",");
  const baseStatsLiteral = vectors.baseStats.join(",");
  const matchupIndexLiteral = vectors.matchupIndex.join(",");
  const matchupsLiteral = vectors.matchups.join(",");
  const nameHashIdsLiteral = nameHash.ids.join(",");
  const aliasHashIdsLiteral = aliasHash.ids.join(",");

  const moduleSource = [
    MODULE_ORIGIN_COMMENT,
    `export const PACK = ${json};`,
    "export const META = PACK.meta;",
    "export const BY_ID = PACK.byId;",
    "export const BY_NAME = PACK.byName;",
    "export const BY_ALIAS = PACK.byAlias;",
    "export const MOVES = PACK.moves;",
    "export const TYPES = PACK.types;",
    `export const SPECIES_STAT_INDEX = new Int32Array([${statIndexLiteral}]);`,
    `export const SPECIES_BASE_STATS = new Uint16Array([${baseStatsLiteral}]);`,
    `export const SPECIES_MATCHUP_INDEX = new Int32Array([${matchupIndexLiteral}]);`,
    `export const SPECIES_MATCHUPS = new Float32Array([${matchupsLiteral}]);`,
    `export const NAME_HASH_SIZE = ${nameHash.size};`,
    `export const NAME_HASH_IDS = new Int32Array([${nameHashIdsLiteral}]);`,
    `export const NAME_HASH_KEYS = ${JSON.stringify(nameHash.keys)};`,
    `export const ALIAS_HASH_SIZE = ${aliasHash.size};`,
    `export const ALIAS_HASH_IDS = new Int32Array([${aliasHashIdsLiteral}]);`,
    `export const ALIAS_HASH_KEYS = ${JSON.stringify(aliasHash.keys)};`,
    "export default PACK;",
    "",
  ].join("\n");
  const moduleBuffer = Buffer.from(moduleSource, "utf8");

  if (checkOnly) {
    await verifyOutputs([
      { filePath: OUTPUT_JSON, buffer: Buffer.from(jsonWithNewline, "utf8") },
      { filePath: OUTPUT_GZ, buffer: gzBuffer },
      { filePath: OUTPUT_MODULE, buffer: moduleBuffer },
    ]);
    log.info("dexpack", "Dexpack verification complete", {
      speciesCount: pack.meta.counts.species,
      moveCount: pack.meta.counts.moves,
    });
    if (!quiet) {
      console.log(
        formatStatus(
          `Dexpack verified (${pack.meta.counts.species} species, ${pack.meta.counts.moves} moves)`,
          "success"
        )
      );
    }
    return;
  }

  const updated = await writeOutputs([
    { filePath: OUTPUT_JSON, contents: jsonWithNewline },
    { filePath: OUTPUT_GZ, contents: gzBuffer },
    { filePath: OUTPUT_MODULE, contents: moduleSource.endsWith("\n") ? moduleSource : `${moduleSource}\n` },
  ]);
  log.info("dexpack", "Dexpack build complete", {
    updated,
    speciesCount: pack.meta.counts.species,
    moveCount: pack.meta.counts.moves,
  });
  if (!quiet) {
    const message = updated
      ? `Dexpack generated → ${path.relative(ROOT, OUTPUT_JSON)} (${pack.meta.counts.species} species, ${pack.meta.counts.moves} moves)`
      : `Dexpack already up to date (${pack.meta.counts.species} species, ${pack.meta.counts.moves} moves)`;
    console.log(formatStatus(message, updated ? "success" : "info"));
  }
}

const invokedDirectly = (() => {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return path.resolve(entry) === __filename;
  } catch {
    return false;
  }
})();

if (invokedDirectly) {
  const cliOptions = parseCliArgs();
  main(cliOptions).catch((error) => {
    const message = error instanceof Error ? error.message : String(error);
    log.error("dexpack", "Dexpack build failed", {
      error: message,
      stack: error instanceof Error ? error.stack : undefined,
    });
    console.log(formatStatus("build_dexpack failed", "error"));
    printError(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
