import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

import {
  buildDexpackContext,
  TYPE_ORDER,
  type DexpackBuildContext,
  type HashTablePayload,
  type SpeciesVectors,
} from "./build_dexpack.js";
import { formatStatus, formatList } from "../src/utils/output-formatter.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const ASSETS_DIR = path.join(ROOT, "assets");
const MANIFEST_PATH = path.join(ASSETS_DIR, "dexpack.v2.json");
const GENERATED_DIR = path.join(ROOT, "src", "dex", "v2");
const GENERATED_ACCESSORS_PATH = path.join(GENERATED_DIR, "accessors.js");

const ALIGNMENT = 8;
const MODULE_HEADER = "// generated by scripts/build-dexpack.ts - do not edit.";

const SECTION_ID = {
  PACK_JSON: 0x0001,
  SPECIES_STAT_INDEX: 0x0100,
  SPECIES_BASE_STATS: 0x0101,
  SPECIES_MATCHUP_INDEX: 0x0102,
  SPECIES_MATCHUPS: 0x0103,
  NAME_HASH_IDS: 0x0200,
  NAME_HASH_KEY_OFFSETS: 0x0201,
  ALIAS_HASH_IDS: 0x0202,
  ALIAS_HASH_KEY_OFFSETS: 0x0203,
  STRINGS_BLOB: 0x0300,
} as const;

type SectionId = (typeof SECTION_ID)[keyof typeof SECTION_ID];

type SectionEntry = {
  id: SectionId;
  name: string;
  data: Buffer;
};

type SectionLayout = {
  id: SectionId;
  name: string;
  offset: number;
  length: number;
};

const textEncoder = new TextEncoder();

function align(value: number, alignment: number): number {
  return (value + alignment - 1) & ~(alignment - 1);
}

function bufferFrom(view: ArrayBufferView): Buffer {
  return Buffer.from(view.buffer, view.byteOffset, view.byteLength);
}

function buildStringTable(nameKeys: string[], aliasKeys: string[]): {
  blob: Uint8Array;
  nameOffsets: Uint32Array;
  aliasOffsets: Uint32Array;
} {
  const offsets = new Map<string, number>();
  const chunks: number[] = [];

  const store = (value: string): number => {
    if (!value) {
      return 0xffffffff;
    }
    const normalized = value;
    if (offsets.has(normalized)) {
      return offsets.get(normalized)!;
    }
    const offset = chunks.length;
    const encoded = textEncoder.encode(normalized);
    for (const byte of encoded) {
      chunks.push(byte);
    }
    chunks.push(0);
    offsets.set(normalized, offset);
    return offset;
  };

  const nameOffsets = new Uint32Array(nameKeys.length);
  nameKeys.forEach((key, index) => {
    nameOffsets[index] = store(key);
  });

  const aliasOffsets = new Uint32Array(aliasKeys.length);
  aliasKeys.forEach((key, index) => {
    aliasOffsets[index] = store(key);
  });

  return {
    blob: Uint8Array.from(chunks),
    nameOffsets,
    aliasOffsets,
  };
}

function buildBinary(sections: SectionEntry[]): { buffer: Buffer; layout: SectionLayout[] } {
  const baseHeaderSize = 8 + sections.length * 12;
  const headerSize = align(baseHeaderSize, ALIGNMENT);
  const header = Buffer.alloc(headerSize);
  header.write("DEX2", 0, "utf8");
  header.writeUInt16LE(2, 4);
  header.writeUInt16LE(sections.length, 6);

  let cursor = 8;
  let dataOffset = headerSize;
  const layout: SectionLayout[] = [];

  for (const entry of sections) {
    dataOffset = align(dataOffset, ALIGNMENT);
    layout.push({ id: entry.id, name: entry.name, offset: dataOffset, length: entry.data.length });
    header.writeUInt16LE(entry.id, cursor);
    header.writeUInt16LE(0, cursor + 2);
    header.writeUInt32LE(dataOffset, cursor + 4);
    header.writeUInt32LE(entry.data.length, cursor + 8);
    cursor += 12;
    dataOffset += entry.data.length;
  }

  const chunks: Buffer[] = [header];
  let currentOffset = header.length;
  layout.forEach((entry, index) => {
    const section = sections[index];
    const padLength = entry.offset - currentOffset;
    if (padLength > 0) {
      chunks.push(Buffer.alloc(padLength));
      currentOffset += padLength;
    }
    chunks.push(section.data);
    currentOffset += section.data.length;
  });

  return { buffer: Buffer.concat(chunks), layout };
}

function vectorsToSections(vectors: SpeciesVectors): SectionEntry[] {
  return [
    {
      id: SECTION_ID.SPECIES_STAT_INDEX,
      name: "species.statIndex",
      data: bufferFrom(Int32Array.from(vectors.statIndex)),
    },
    {
      id: SECTION_ID.SPECIES_BASE_STATS,
      name: "species.baseStats",
      data: bufferFrom(Uint16Array.from(vectors.baseStats)),
    },
    {
      id: SECTION_ID.SPECIES_MATCHUP_INDEX,
      name: "species.matchupIndex",
      data: bufferFrom(Int32Array.from(vectors.matchupIndex)),
    },
    {
      id: SECTION_ID.SPECIES_MATCHUPS,
      name: "species.matchups",
      data: bufferFrom(Float32Array.from(vectors.matchups)),
    },
  ];
}

function hashTablesToSections(nameHash: HashTablePayload, aliasHash: HashTablePayload, strings: {
  nameOffsets: Uint32Array;
  aliasOffsets: Uint32Array;
}): SectionEntry[] {
  return [
    {
      id: SECTION_ID.NAME_HASH_IDS,
      name: "hash.name.ids",
      data: bufferFrom(Int32Array.from(nameHash.ids)),
    },
    {
      id: SECTION_ID.NAME_HASH_KEY_OFFSETS,
      name: "hash.name.keys",
      data: bufferFrom(strings.nameOffsets),
    },
    {
      id: SECTION_ID.ALIAS_HASH_IDS,
      name: "hash.alias.ids",
      data: bufferFrom(Int32Array.from(aliasHash.ids)),
    },
    {
      id: SECTION_ID.ALIAS_HASH_KEY_OFFSETS,
      name: "hash.alias.keys",
      data: bufferFrom(strings.aliasOffsets),
    },
  ];
}

async function ensureDirs(): Promise<void> {
  await fs.mkdir(ASSETS_DIR, { recursive: true });
  await fs.mkdir(GENERATED_DIR, { recursive: true });
}

type CliOptions = { check?: boolean; quiet?: boolean };

function parseCliArgs(): CliOptions {
  const args = process.argv.slice(2);
  const options: CliOptions = { check: false, quiet: false };
  for (const arg of args) {
    if (arg === "--check") {
      options.check = true;
    } else if (arg === "--quiet") {
      options.quiet = true;
    } else if (arg === "--help" || arg === "-h") {
      console.log(
        formatList([
          "Usage: tsx scripts/build-dexpack.ts [--check] [--quiet]",
          "--check   Verify existing outputs without writing",
          "--quiet   Suppress success logs",
        ])
      );
      process.exit(0);
    } else {
      console.log(formatStatus(`Unknown flag: ${arg}`, "warning"));
    }
  }
  return options;
}

async function loadExistingManifest(): Promise<Record<string, unknown> | null> {
  try {
    const raw = await fs.readFile(MANIFEST_PATH, "utf8");
    return JSON.parse(raw) as Record<string, unknown>;
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

async function writeIfChanged(filePath: string, data: string | Buffer): Promise<boolean> {
  try {
    const existing = await fs.readFile(filePath);
    const next = typeof data === "string" ? Buffer.from(data, "utf8") : data;
    if (existing.equals(next)) {
      return false;
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code !== "ENOENT") {
      throw error;
    }
  }
  await fs.writeFile(filePath, data);
  return true;
}

async function cleanOldBinaries(currentFilename: string): Promise<void> {
  const entries = await fs.readdir(ASSETS_DIR);
  const targets = entries.filter((name) => name.startsWith("dexpack.v2.") && name.endsWith(".bin") && name !== currentFilename);
  await Promise.all(
    targets.map((name) => fs.unlink(path.join(ASSETS_DIR, name)).catch(() => undefined)),
  );
}

function buildSections(context: DexpackBuildContext): { sections: SectionEntry[]; stringsLength: number } {
  const { pack, vectors, nameHash, aliasHash } = context;
  const strings = buildStringTable(nameHash.keys, aliasHash.keys);

  const packJson = Buffer.from(`${JSON.stringify(pack)}\n`, "utf8");
  const baseSections: SectionEntry[] = [
    { id: SECTION_ID.PACK_JSON, name: "pack.json", data: packJson },
    { id: SECTION_ID.STRINGS_BLOB, name: "strings", data: bufferFrom(strings.blob) },
  ];

  const vectorSections = vectorsToSections(vectors);
  const hashSections = hashTablesToSections(nameHash, aliasHash, strings);

  return {
    sections: [...baseSections, ...vectorSections, ...hashSections],
    stringsLength: strings.blob.length,
  };
}

function summarizeLayout(layout: SectionLayout[]) {
  return layout.map((entry) => ({ id: entry.id, name: entry.name, offset: entry.offset, length: entry.length }));
}

async function writeAccessors(manifest: {
  hash: string;
  binary: string;
  counts: { species: number; moves: number };
}): Promise<boolean> {
  const source = `${MODULE_HEADER}\nimport path from \"node:path\";\nimport fs from \"node:fs/promises\";\n\nexport const DEX_V2_MANIFEST_HASH = \"${manifest.hash}\";\nexport const DEX_V2_BINARY = \"${manifest.binary}\";\nexport const DEX_V2_COUNTS = Object.freeze({ species: ${manifest.counts.species}, moves: ${manifest.counts.moves} });\n\nexport async function readDexV2Binary(rootDir) {\n  const filePath = path.join(rootDir, \"assets\", DEX_V2_BINARY);\n  return fs.readFile(filePath);\n}\n`;
  return writeIfChanged(GENERATED_ACCESSORS_PATH, source);
}

async function main(options: CliOptions = {}): Promise<void> {
  const quiet = Boolean(options.quiet);
  await ensureDirs();

  const context = await buildDexpackContext();
  const { sections, stringsLength } = buildSections(context);
  const { buffer, layout } = buildBinary(sections);
  const hash = createHash("sha256").update(buffer).digest("hex");
  const binaryFilename = `dexpack.v2.${hash}.bin`;
  const binaryPath = path.join(ASSETS_DIR, binaryFilename);

  if (options.check) {
    const manifest = await loadExistingManifest();
    if (!manifest) {
      throw new Error("dexpack.v2 manifest is missing — run without --check to generate it.");
    }
    const recordedHash = manifest["hash"];
    const recordedBinary = manifest["binary"];
    if (recordedHash !== hash || recordedBinary !== binaryFilename) {
      throw new Error("dexpack.v2 artifacts are stale — run scripts/build-dexpack.ts to regenerate.");
    }
    if (!quiet) {
      console.log(
        formatStatus(
          `dexpack.v2 verified (${context.pack.meta.counts.species} species, ${context.pack.meta.counts.moves} moves)`,
          "success"
        )
      );
    }
    return;
  }

  await fs.writeFile(binaryPath, buffer);
  await cleanOldBinaries(binaryFilename);

  const manifest = {
    schema: "dexpack.v2",
    generatedAt: context.pack.meta.generatedAt,
    counts: context.pack.meta.counts,
    hash,
    binary: binaryFilename,
    alignment: ALIGNMENT,
    stringsLength,
    layout: summarizeLayout(layout),
    typeOrder: TYPE_ORDER,
  };
  const manifestChanged = await writeIfChanged(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  const accessorsChanged = await writeAccessors({ hash, binary: binaryFilename, counts: context.pack.meta.counts });

  if (!quiet) {
    const updatedParts = [manifestChanged ? "manifest" : null, accessorsChanged ? "accessors" : null]
      .filter(Boolean)
      .join(", ");
    const suffix = updatedParts ? ` (${updatedParts})` : "";
    console.log(formatStatus(`dexpack.v2 generated → ${binaryFilename}${suffix}`, "success"));
  }
}

const invokedDirectly = (() => {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return path.resolve(entry) === __filename;
  } catch {
    return false;
  }
})();

if (invokedDirectly) {
  const options = parseCliArgs();
  main(options).catch((error) => {
    console.log(formatStatus("build-dexpack failed", "error"));
    console.error(error);
    process.exitCode = 1;
  });
}
