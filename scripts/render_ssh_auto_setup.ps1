#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Automated Render SSH key setup and configuration
.DESCRIPTION
    Installs the Render SSH key from environment file, configures SSH config,
    and sets up Windows registry for automated access. No user interaction required.
.PARAMETER Force
    Force overwrite existing keys and configuration
.EXAMPLE
    .\render_ssh_auto_setup.ps1
.EXAMPLE
    .\render_ssh_auto_setup.ps1 -Force
#>

param(
    [switch]$Force
)

$ErrorActionPreference = "Stop"

Write-Host "🤖 Automated Render SSH Setup" -ForegroundColor Cyan
Write-Host "==============================" -ForegroundColor Cyan
Write-Host ""

# Load SSH key from environment file
$envFile = "secrets/Infinity-Gauntlet.env"
if (-not (Test-Path $envFile)) {
    Write-Host "❌ Environment file not found: $envFile" -ForegroundColor Red
    exit 1
}

$renderSshKey = Get-Content $envFile | Select-String -Pattern '^RENDER_SSH_KEY=' | ForEach-Object { 
    ($_ -split '=', 2)[1].Trim() 
}

if (-not $renderSshKey) {
    Write-Host "❌ RENDER_SSH_KEY not found in $envFile" -ForegroundColor Red
    Write-Host "   Add line: RENDER_SSH_KEY=ssh-ed25519 AAAAC3Nza..." -ForegroundColor Gray
    exit 1
}

Write-Host "✅ Found RENDER_SSH_KEY in environment file" -ForegroundColor Green
Write-Host ""

# Create SSH directory
$sshDir = Join-Path $env:USERPROFILE ".ssh"
if (-not (Test-Path $sshDir)) {
    Write-Host "📁 Creating SSH directory: $sshDir" -ForegroundColor Yellow
    New-Item -ItemType Directory -Path $sshDir -Force | Out-Null
    
    # Set permissions (owner only)
    $acl = Get-Acl $sshDir
    $acl.SetAccessRuleProtection($true, $false)
    $rule = New-Object System.Security.AccessControl.FileSystemAccessRule(
        $env:USERNAME, "FullControl", "ContainerInherit,ObjectInherit", "None", "Allow"
    )
    $acl.AddAccessRule($rule)
    Set-Acl $sshDir $acl
    Write-Host "✅ SSH directory created with secure permissions" -ForegroundColor Green
}

# Install public key to authorized_keys (for reference)
$authorizedKeysPath = Join-Path $sshDir "render_ed25519.pub"
$privateKeyPath = Join-Path $sshDir "render_ed25519"

if ((Test-Path $authorizedKeysPath) -and -not $Force) {
    Write-Host "⚠️  Render public key already exists: $authorizedKeysPath" -ForegroundColor Yellow
    Write-Host "   Use -Force to overwrite" -ForegroundColor Gray
} else {
    Write-Host "📝 Installing Render public key..." -ForegroundColor Cyan
    Set-Content -Path $authorizedKeysPath -Value $renderSshKey -NoNewline
    Write-Host "✅ Public key installed: $authorizedKeysPath" -ForegroundColor Green
}

Write-Host ""

# Check if private key exists (users must have the private key separately)
if (-not (Test-Path $privateKeyPath)) {
    Write-Host "⚠️  Private key not found: $privateKeyPath" -ForegroundColor Yellow
    Write-Host "   This script installs the PUBLIC key only" -ForegroundColor Gray
    Write-Host "   Private key must be obtained from secure source" -ForegroundColor Gray
    Write-Host ""
    Write-Host "💡 If you have the private key:" -ForegroundColor Cyan
    Write-Host "   1. Place it at: $privateKeyPath" -ForegroundColor White
    Write-Host "   2. Set permissions: icacls `"$privateKeyPath`" /inheritance:r /grant:r `"${env:USERNAME}:R`"" -ForegroundColor White
    Write-Host "   3. Re-run this script" -ForegroundColor White
    Write-Host ""
}

# Configure SSH config file
$sshConfigPath = Join-Path $sshDir "config"
$renderConfigExists = $false

if (Test-Path $sshConfigPath) {
    $content = Get-Content $sshConfigPath -Raw
    $renderConfigExists = $content -match "Host \*\.render\.com"
}

if (-not $renderConfigExists -or $Force) {
    Write-Host "⚙️  Configuring SSH config..." -ForegroundColor Cyan
    
    $configEntry = @"

# Render SSH Configuration (auto-generated by render_ssh_auto_setup.ps1)
# Based on official Render documentation: https://render.com/docs/ssh
Host *.render.com
    IdentityFile $privateKeyPath
    StrictHostKeyChecking accept-new
    ServerAliveInterval 60
    ServerAliveCountMax 3
    AddKeysToAgent yes
    UseKeychain yes

# Render region shortcuts
Host render-oregon
    HostName ssh.oregon.render.com

Host render-ohio
    HostName ssh.ohio.render.com

Host render-virginia
    HostName ssh.virginia.render.com

Host render-frankfurt
    HostName ssh.frankfurt.render.com

Host render-singapore
    HostName ssh.singapore.render.com

"@
    
    if ($Force -and (Test-Path $sshConfigPath)) {
        # Backup existing config
        $backupPath = "$sshConfigPath.backup.$(Get-Date -Format 'yyyyMMdd_HHmmss')"
        Copy-Item $sshConfigPath $backupPath
        Write-Host "📦 Backed up existing config to: $backupPath" -ForegroundColor Yellow
    }
    
    Add-Content -Path $sshConfigPath -Value $configEntry
    Write-Host "✅ SSH config updated: $sshConfigPath" -ForegroundColor Green
} else {
    Write-Host "✅ SSH config already configured" -ForegroundColor Green
}

Write-Host ""

# Add Render's public keys to known_hosts
$knownHostsPath = Join-Path $sshDir "known_hosts"
$renderKnownHosts = @"
# Render SSH public keys (auto-added by render_ssh_auto_setup.ps1)
ssh.oregon.render.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIFON8eay2FgHDBIVOLxWn/AWnsDJhCVvlY1igWEFoLD2
ssh.ohio.render.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAINMjC1BfZQ3CYotN1/EqI48hvBpZ80zfgRdK8NpP58v1
ssh.virginia.render.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIJ6uO0jKQX9IjefnLz+pxTgfPhsPBhNuvxmvCFrxqxAM
ssh.frankfurt.render.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAILg6kMvQOQjMREehk1wvBKsfe1I3+acRuS8cVSdLjinK
ssh.singapore.render.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIGVcVcsy7RXA60ZyHs/OMS5aQj4YQy7Qn2nJCXHz4zLA
"@

$needsKnownHosts = $true
if (Test-Path $knownHostsPath) {
    $content = Get-Content $knownHostsPath -Raw
    if ($content -match "ssh\.oregon\.render\.com") {
        $needsKnownHosts = $false
    }
}

if ($needsKnownHosts -or $Force) {
    Write-Host "🔐 Adding Render's public keys to known_hosts..." -ForegroundColor Cyan
    if ($Force -and (Test-Path $knownHostsPath)) {
        Add-Content -Path $knownHostsPath -Value "`n$renderKnownHosts"
    } else {
        Add-Content -Path $knownHostsPath -Value $renderKnownHosts
    }
    Write-Host "✅ Known hosts updated" -ForegroundColor Green
} else {
    Write-Host "✅ Known hosts already configured" -ForegroundColor Green
}

Write-Host ""

# Configure Windows registry for SSH agent (OpenSSH service)
Write-Host "🔧 Configuring Windows OpenSSH service..." -ForegroundColor Cyan

try {
    # Ensure ssh-agent service is installed
    $sshAgentService = Get-Service -Name "ssh-agent" -ErrorAction SilentlyContinue
    
    if ($sshAgentService) {
        # Set service to automatic startup
        Set-Service -Name "ssh-agent" -StartupType Automatic
        Write-Host "✅ ssh-agent service set to automatic startup" -ForegroundColor Green
        
        # Start the service if not running
        if ($sshAgentService.Status -ne "Running") {
            Start-Service -Name "ssh-agent"
            Write-Host "✅ ssh-agent service started" -ForegroundColor Green
        } else {
            Write-Host "✅ ssh-agent service already running" -ForegroundColor Green
        }
    } else {
        Write-Host "⚠️  OpenSSH ssh-agent service not found" -ForegroundColor Yellow
        Write-Host "   Install OpenSSH Client via Windows Settings → Apps → Optional Features" -ForegroundColor Gray
    }
} catch {
    Write-Host "⚠️  Could not configure ssh-agent service: $($_.Exception.Message)" -ForegroundColor Yellow
    Write-Host "   You may need to run this script as Administrator" -ForegroundColor Gray
}

Write-Host ""

# Create environment variable for SSH key path (for automation)
Write-Host "🌍 Setting environment variables..." -ForegroundColor Cyan

try {
    # Set user-level environment variable
    [System.Environment]::SetEnvironmentVariable("RENDER_SSH_KEY_PATH", $privateKeyPath, "User")
    Write-Host "✅ Environment variable set: RENDER_SSH_KEY_PATH=$privateKeyPath" -ForegroundColor Green
    
    # Update current session
    $env:RENDER_SSH_KEY_PATH = $privateKeyPath
    
} catch {
    Write-Host "⚠️  Could not set environment variable: $($_.Exception.Message)" -ForegroundColor Yellow
}

Write-Host ""

# Summary
Write-Host "🎉 Automated Setup Complete!" -ForegroundColor Green
Write-Host ""
Write-Host "✅ Configuration Summary:" -ForegroundColor Cyan
Write-Host "   • Public key installed: $authorizedKeysPath" -ForegroundColor White
Write-Host "   • Private key path: $privateKeyPath" -ForegroundColor White
Write-Host "   • SSH config updated: $sshConfigPath" -ForegroundColor White
Write-Host "   • Known hosts updated: $knownHostsPath" -ForegroundColor White
Write-Host "   • ssh-agent service configured" -ForegroundColor White
Write-Host "   • Environment variable: RENDER_SSH_KEY_PATH" -ForegroundColor White
Write-Host ""

if (-not (Test-Path $privateKeyPath)) {
    Write-Host "⚠️  IMPORTANT: Private key not found!" -ForegroundColor Yellow
    Write-Host "   You must obtain the private key separately and place it at:" -ForegroundColor White
    Write-Host "   $privateKeyPath" -ForegroundColor Gray
    Write-Host ""
    Write-Host "   After placing the private key:" -ForegroundColor White
    Write-Host "   1. Set secure permissions:" -ForegroundColor White
    Write-Host "      icacls `"$privateKeyPath`" /inheritance:r /grant:r `"${env:USERNAME}:R`"" -ForegroundColor Gray
    Write-Host "   2. Test connection:" -ForegroundColor White
    Write-Host "      npm run render:ssh-connect" -ForegroundColor Gray
    Write-Host ""
} else {
    Write-Host "✅ Ready to connect!" -ForegroundColor Green
    Write-Host "   Test connection: npm run render:ssh-connect" -ForegroundColor White
    Write-Host "   Or directly: ssh srv-d3snk2ndiees73cn709g@ssh.virginia.render.com" -ForegroundColor White
    Write-Host ""
}

Write-Host "📚 Documentation:" -ForegroundColor Cyan
Write-Host "   • SSH Setup: docs/deployment/render-ssh-automation.md" -ForegroundColor Gray
Write-Host "   • Environment: secrets/Infinity-Gauntlet.env" -ForegroundColor Gray
Write-Host ""
